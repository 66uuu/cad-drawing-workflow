def _mk_dst(src, target):
    """轴网 → 「开间基本相等、末跨吸收余量」的目标网格，保证严格闭合"""
    n = len(src) - 1
    base = math.ceil(target / n)
    return [0.0] + [base * i for i in range(1, n)] + [float(target)]


def _mk_mapper(src, dst):
    """分段线性映射（首尾开间线性外推，保证轴伸出量不畸变）"""
    import bisect as _bisect
    spans = [dst[i + 1] - dst[i] for i in range(len(dst) - 1)]
    sspans = [src[i + 1] - src[i] for i in range(len(src) - 1)]

    def mp(v):
        if v <= src[0]:
            return dst[0] + (v - src[0]) * spans[0] / sspans[0]
        if v >= src[-1]:
            return dst[-1] + (v - src[-1]) * spans[-1] / sspans[-1]
        i = _bisect.bisect_right(src, v) - 1
        return dst[i] + (v - src[i]) * spans[i] / sspans[i]

    return mp


