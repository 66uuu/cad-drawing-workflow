def _rescale_qty(text, k):
    """把 '8mm / 520㎡' 中的工程量按 k 缩放；k == 1 或无数字时原样返回"""
    if k == 1 or not text or text == "—":
        return text
    if "/" in text:
        head, _, tail = text.rpartition("/")
        pre, tail = head.rstrip() + " / ", tail.strip()
    else:
        tail, pre = text, ""
    m = re.search(r"\d+(\.\d+)?", tail)
    if not m:
        return text
    val = float(m.group(0)) * k
    new = int(round(val)) if val >= 50 else round(val, 1)
    new = int(new) if isinstance(new, float) and abs(new - round(new)) < 1e-9 else new
    return (pre + tail[:m.start()] + str(new) + tail[m.end():]).strip()


