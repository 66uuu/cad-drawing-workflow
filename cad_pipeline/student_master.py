# ============ 十、机电末端（数量为自检硬数字） ============
def _grid(x1, y1, x2, y2, sx, sy, inset=0):
    """在矩形内生成网格点，返回 [(x,y), ...]"""
    pts = []
    x = x1 + inset
    while x <= x2 - inset:
        y = y1 + inset
        while y <= y2 - inset:
            pts.append((x, y))
            y += sy
        x += sx
    return pts

def _in_core(x, y, m=300):
    return (CORE_X1 - m < x < CORE_X2 + m) and (CORE_Y1 - m < y < CORE_Y2 + m)

def gen_sprinklers():
    """喷淋 110：中危险 I 级 12.5㎡/个，间距 ≤3.4m，距墙 ≤1.7m"""
    pts = _grid(1700, 1700, OUT_X - 1700, OUT_Y - 1700, 3400, 3400)
    pts = [p for p in pts if not _in_core(*p)]
    # 微调至 110：优先从候选中删中位，不足则在半步网格补（不出建筑外框）
    while len(pts) > 110:
        pts.pop(len(pts) // 2)
    k = 0
    while len(pts) < 110 and k < 600:
        k += 1
        x = 1700 + (k % 12) * 3400 + 1700
        y = 1700 + (k // 12) * 3400 + 1700
        if x <= OUT_X - 500 and y <= OUT_Y - 500 and not _in_core(x, y) and (x, y) not in pts:
            pts.append((x, y))
    return pts[:110]

