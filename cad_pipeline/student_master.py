def gen_vents():
    """风口 35：600×600 散流器，约每 40㎡ 一个"""
    pts = _grid(2500, 2500, OUT_X - 2500, OUT_Y - 2500, 6300, 6300)
    pts = [p for p in pts if not _in_core(*p, m=800)]
    while len(pts) > 35:
        pts.pop(len(pts) // 2)
    # 不足时在网格半步位置补点（保证落在建筑内部，不补到幕墙外）
    k = 0
    while len(pts) < 35 and k < 600:
        k += 1
        x = 2500 + (k % 6) * 6300 + 3150
        y = 2500 + (k // 6) * 6300 + 3150
        if x <= OUT_X - 500 and y <= OUT_Y - 500 and not _in_core(x, y) and (x, y) not in pts:
            pts.append((x, y))
    return pts[:35]

